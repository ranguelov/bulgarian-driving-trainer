# 1) дефисная чистка
n_dehy = 0
for q in app:
    nq = dehy(q["question"])
    if nq != q["question"]: q["question"] = nq; n_dehy += 1
    for a in q["answers"]:
        na = dehy(a["text"])
        if na != a["text"]: a["text"] = na; n_dehy += 1

